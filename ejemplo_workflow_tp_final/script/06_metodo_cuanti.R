# PCA o metodo cuantitativo elegido 

# Como tienen que realizar algunos métodos cuantitativos, lo mejor es seguir con un 
# script nuevo para hacer cada uno de ellos
# Es decir, si tienen que aplicar PCA y Regresion
# Un script es para PCA y guardan los resultados en output
# Otro script es para regresión y guardan los resultados en output 
# los script pese a ser independientes y no necesariamente tener un orden tan estricto
# deben estar numerados siempre, de forma tal de orientar a los usuarios a los que se les comparte 

# El script del metodo cuantitativo elegido no debe tener partes de limpieza de datos
# Eso tiene que ya estar resuelto previamente, por lo que en este caso ya tomarian los resultados 
# del script que los limpio

# Es decir, en este caso deberia tomar las mismas tablas que usé para graficar, en lugar de las iniciales
# Ya que las de los graficos ya están "curadas"
